export function normalizeColumnKey(key: string): string {
  if (!key) return '';
  return key
    .toLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\(\)\[\]\/\-\_\:\.]/g, '')
    .replace(/\s+/g, '')
    .trim();
}

