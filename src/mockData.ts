export function decomposeArabicFullName(rawName: string, seed: number = 1): {
  cleanFullName: string;
  rank: string;
  firstName: string;
  fatherName: string;
  grandfatherName: string;
  greatGrandfatherName: string;
  clan: string;
} {
  let nameStr = (rawName || '').trim();
  let detectedRank = '';

  // 1. Detect and strip leading military rank
  const normForRank = normalizeArabic(nameStr);
  for (const rank of MILITARY_RANKS) {
    if (normForRank.startsWith(rank)) {
      detectedRank = nameStr.slice(0, rank.length).trim();
      nameStr = nameStr.slice(rank.length).trim();
      break;
    }
  }

  // Patronymic fallbacks so names are always complete 4-part names + clan
  const defaultFathers = ['خليل', 'عباس', 'كمال', 'ضياء', 'جاسم', 'كريم', 'حسين', 'سلمان', 'حميد', 'داود'];
  const defaultGrandfathers = ['إبراهيم', 'مراد', 'داود', 'إسماعيل', 'صالح', 'علي', 'نعمة', 'رشيد', 'مهدي', 'قاسم'];
  const defaultGreatGrandfathers = ['حسن', 'كاظم', 'عيسى', 'خضير', 'عبد الله', 'طه', 'عمران', 'فاضل', 'محمود', 'شريف'];
  const defaultClans = ['الساعدي', 'الكعبي', 'البياتي', 'القيسي', 'الشمري', 'الجبوري', 'التميمي', 'العبيدي', 'الخزرجي', 'النداوي'];

  const words = nameStr.split(/\s+/).filter(Boolean);

  let firstName = '';
  let fatherName = '';
  let grandfatherName = '';
  let greatGrandfatherName = '';
  let clan = '';

  if (words.length >= 5) {
    firstName = words[0];
    fatherName = words[1];
    grandfatherName = words[2];
    greatGrandfatherName = words[3];
    clan = words.slice(4).join(' ');
  } else if (words.length === 4) {
    firstName = words[0];
    fatherName = words[1];
    grandfatherName = words[2];
    greatGrandfatherName = defaultGreatGrandfathers[seed % defaultGreatGrandfathers.length];
    clan = words[3];
  } else if (words.length === 3) {
    firstName = words[0];
    fatherName = words[1];
    grandfatherName = defaultGrandfathers[seed % defaultGrandfathers.length];
    greatGrandfatherName = defaultGreatGrandfathers[seed % defaultGreatGrandfathers.length];
    clan = words[2];
  } else if (words.length === 2) {
    firstName = words[0];
    fatherName = defaultFathers[seed % defaultFathers.length];
    grandfatherName = defaultGrandfathers[seed % defaultGrandfathers.length];
    greatGrandfatherName = defaultGreatGrandfathers[seed % defaultGreatGrandfathers.length];
    clan = words[1];
  } else if (words.length === 1) {
    firstName = words[0];
    fatherName = defaultFathers[seed % defaultFathers.length];
    grandfatherName = defaultGrandfathers[seed % defaultGrandfathers.length];
    greatGrandfatherName = defaultGreatGrandfathers[seed % defaultGreatGrandfathers.length];
    clan = defaultClans[seed % defaultClans.length];
  } else {
    firstName = 'منتسب';
    fatherName = defaultFathers[seed % defaultFathers.length];
    grandfatherName = defaultGrandfathers[seed % defaultGrandfathers.length];
    greatGrandfatherName = defaultGreatGrandfathers[seed % defaultGreatGrandfathers.length];
    clan = defaultClans[seed % defaultClans.length];
  }

  const cleanFullName = `${firstName} ${fatherName} ${grandfatherName} ${greatGrandfatherName} ${clan}`;

  return {
    cleanFullName,
    rank: detectedRank,
    firstName,
    fatherName,
    grandfatherName,
    greatGrandfatherName,
    clan
  };
}

